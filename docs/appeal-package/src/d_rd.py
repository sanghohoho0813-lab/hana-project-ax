def growth_svg() -> str:
    pts = [("10-28", "엔진 1·2차", 113), ("11-16", "0.4.0", 625), ("11-16", "0.4.1", 629), ("11-16", "0.4.3", 637), ("11-16", "0.5.0", 669), ("11-16", "0.6.0", 686), ("11-18", "0.6.1", 746)]
    W, H, x0, yb = 700, 210, 40, 170
    mx = 800
    bw = (W - x0 - 10) / len(pts)
    g = [f'<svg viewBox="0 0 {W} {H}" xmlns="http://www.w3.org/2000/svg" font-family="Pretendard">']
    for v in (0, 200, 400, 600, 800):
        y = yb - v / mx * 145
        g.append(f'<line x1="{x0}" y1="{y:.1f}" x2="{W - 10}" y2="{y:.1f}" stroke="#e3e7ea"/><text x="{x0 - 6}" y="{y + 4:.1f}" text-anchor="end" font-size="10" fill="#75818a">{v}</text>')
    for i, (d, v_, n) in enumerate(pts):
        cx = x0 + bw * i + bw / 2
        h = n / mx * 145
        last = i == len(pts) - 1
        g.append(f'<rect x="{cx - bw * 0.3:.1f}" y="{yb - h:.1f}" width="{bw * 0.6:.1f}" height="{h:.1f}" rx="3" fill="{"#127566" if last else "#9ccfc3"}"/>')
        g.append(f'<text x="{cx:.1f}" y="{yb - h - 5:.1f}" text-anchor="middle" font-size="11.5" font-weight="850" fill="#10283a">{n}</text>')
        g.append(f'<text x="{cx:.1f}" y="{yb + 15}" text-anchor="middle" font-size="10.5" font-weight="750" fill="#43505a">{v_}</text>')
        g.append(f'<text x="{cx:.1f}" y="{yb + 29}" text-anchor="middle" font-size="9.5" fill="#75818a">{d}</text>')
    g.append("</svg>")
    return "".join(g)


