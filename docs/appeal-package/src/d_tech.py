def day_svg(hm) -> str:
    """기사 하루 일정 — 예정 vs ‘1시간 더’ 보고 뒤 계산 (11:00 기준 분)"""
    x0, ppm = 92, 2.1  # 11:00 위치 · 1분 폭
    X = lambda m: x0 + m * ppm  # noqa: E731
    def blk(y, a, b, fill, txt, tc="#fff", stroke="none"):
        return (f'<rect x="{X(a):.1f}" y="{y}" width="{(b - a) * ppm:.1f}" height="30" rx="5" fill="{fill}" stroke="{stroke}" stroke-dasharray="4 3"/>'
                f'<text x="{X((a + b) / 2):.1f}" y="{y + 19.5}" text-anchor="middle" font-size="11.5" font-weight="750" fill="{tc}">{txt}</text>')
    g = ['<svg viewBox="0 0 740 196" xmlns="http://www.w3.org/2000/svg" font-family="Pretendard">']
    for m in range(0, 301, 30):
        g.append(f'<line x1="{X(m)}" y1="20" x2="{X(m)}" y2="170" stroke="#e3e7ea"/>')
        if m % 60 == 0:
            g.append(f'<text x="{X(m)}" y="186" text-anchor="middle" font-size="10.5" fill="#75818a">{hm(m)}</text>')
    g.append('<text x="6" y="56" font-size="11.5" font-weight="800" fill="#10283a">예정</text>')
    g.append('<text x="6" y="126" font-size="11.5" font-weight="800" fill="#c0442c">보고 뒤</text><text x="6" y="140" font-size="9.5" fill="#75818a">(계산)</text>')
    y1, y2 = 36, 106
