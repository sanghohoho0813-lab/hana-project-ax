def sweep_svg() -> str:
    """선행 현장 예상 종료를 5분씩 늦출 때 — 후속 현장 여유와 등급, 기존 겹침 검사 결과 (docs/evidence/delay-sweep.json)"""
    d = json.loads((REPO / "docs/evidence/delay-sweep.json").read_text())
    rows = d["rows"]
    col_ = {"없음": "#9ccfc3", "주의": "#e9c46a", "중간": "#f0a35e", "높음": "#e0806b", "매우 높음": "#c0442c"}
    W, H, x0, y0z = 720, 250, 70, 92  # y0z = 여유 0 위치
    sc = 3.6
    g = [f'<svg viewBox="0 0 {W} {H}" xmlns="http://www.w3.org/2000/svg" font-family="Pretendard">']
    for v in (10, 0, -10, -20, -30):
        y = y0z - v * sc
        g.append(f'<line x1="{x0}" y1="{y}" x2="{W - 10}" y2="{y}" stroke="{"#10283a" if v == 0 else "#e3e7ea"}" stroke-width="{1.4 if v == 0 else 1}"/>')
        g.append(f'<text x="{x0 - 8}" y="{y + 4}" text-anchor="end" font-size="10.5" fill="#75818a">{"+" if v > 0 else ""}{v}분</text>')
    bw = (W - x0 - 20) / len(rows)
    for i, r in enumerate(rows):
        cx = x0 + bw * i + bw / 2
        v = r["slack"]
        y, h = (y0z - v * sc, v * sc) if v >= 0 else (y0z, -v * sc)
        g.append(f'<rect x="{cx - bw * 0.32:.1f}" y="{y:.1f}" width="{bw * 0.64:.1f}" height="{max(h, 2):.1f}" rx="3" fill="{col_[r["grade"]]}"/>')
        g.append(f'<text x="{cx:.1f}" y="{(y - 5) if v >= 0 else (y + h + 13):.1f}" text-anchor="middle" font-size="10" font-weight="800" fill="#18242d">{r["grade"]}</text>')
        g.append(f'<text x="{cx:.1f}" y="{H - 42}" text-anchor="middle" font-size="10.5" fill="#43505a">{r["expectedEnd"]}</text>')
        g.append(f'<text x="{cx:.1f}" y="{H - 24}" text-anchor="middle" font-size="12" font-weight="850" fill="{"#c0442c" if r["engineDetected"] else "#9aa4ab"}">{"●" if r["engineDetected"] else "○"}</text>')
        g.append(f'<text x="{cx:.1f}" y="{H - 7}" text-anchor="middle" font-size="12" font-weight="850" fill="#9aa4ab">{"●" if r["baselineDetected"] else "○"}</text>')
    g.append(f'<text x="{x0 - 8}" y="{H - 42}" text-anchor="end" font-size="9.5" fill="#75818a">A 예상 종료</text>')
    g.append(f'<text x="{x0 - 8}" y="{H - 24}" text-anchor="end" font-size="9.5" font-weight="800" fill="#c0442c">연쇄위험 엔진</text>')
    g.append(f'<text x="{x0 - 8}" y="{H - 7}" text-anchor="end" font-size="9.5" font-weight="800" fill="#75818a">기존 겹침 검사</text>')
    g.append(f'<text x="{x0}" y="14" font-size="10.5" font-weight="800" fill="#10283a">후속 현장(B) 여유 · 부족</text>')
    g.append("</svg>")
    return "".join(g)


